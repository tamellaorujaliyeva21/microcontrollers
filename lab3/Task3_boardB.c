void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
    {
        if (ic_skip) { ic_skip = 0; return; }   /* counter was free-running before 1st reset */
        ic_period = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
        ic_high   = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_2);
        ic_stamp  = HAL_GetTick();
        ic_new    = 1;
    }
}

static void uart_print(const char *s)
{
    HAL_UART_Transmit(&huart2, (uint8_t *)s, (uint16_t)strlen(s), 50);
}
